alunos = ["Ana", "Larissa", "Thay", "Paula", "Rebeca"]
print("Lista Inicial", alunos)

alunos.append("Vitória")
print("Após adicionar: ", alunos)

alunos.pop(2)
print("Após remover o 3° aluno:", alunos)

alunos.reverse()
print("Lista invertida:", alunos)

alunos.sort()
print("Lista ordenada:", alunos)